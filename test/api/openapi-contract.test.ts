import { describe, expect, test } from 'bun:test'
import path from 'node:path'
import swaggerJsdoc from 'swagger-jsdoc'
import { z } from 'zod'
import { createSignedTextDownload } from '../../src/core/services/texts/signed-text-download'

const schema = z.object({
  paths: z.record(z.string(), z.record(z.string(), z.unknown())),
  components: z.object({
    schemas: z.record(z.string(), z.unknown()),
  }),
})

describe('generated OpenAPI contracts', () => {
  const specification = schema.parse(
    swaggerJsdoc({
      failOnErrors: true,
      definition: {
        openapi: '3.0.0',
        info: { title: 'Contract test', version: '1' },
      },
      apis: [path.resolve(__dirname, '../../src/api/routes/*.ts')],
    })
  )

  test('documents all job operations with the actual jobs authentication', () => {
    // Given / When: the annotations are parsed by the shipping generator library.
    const routes = [
      ['/api/jobs/process-message', 'post'],
      ['/api/jobs/process-message/enhanced', 'post'],
      ['/api/jobs/{jobId}/status', 'get'],
      ['/api/jobs/{jobId}/result', 'get'],
      ['/api/jobs/{jobId}/result/enhanced', 'get'],
    ]
    // Then: all mounted operations have the same security scheme as the middleware.
    for (const [route, method] of routes) {
      const operation = z
        .object({ security: z.unknown() })
        .parse(specification.paths[route]?.[method])
      expect(operation.security).toEqual([{ JobsBearerAuth: [] }])
    }
    const legacy = z
      .object({ security: z.unknown() })
      .parse(specification.paths['/api/process-message']?.post)
    expect(legacy.security).toEqual([])
  })

  test('requires both signed-download response fields', () => {
    // Given / When: the completed result schema is generated.
    const result = z
      .object({
        required: z.array(z.string()),
        properties: z.record(
          z.string(),
          z.object({ type: z.string(), format: z.string().optional() }).passthrough()
        ),
      })
      .parse(specification.components.schemas.ProcessMessageJobResult)
    // Then: clients can consume the URL and its expiry together.
    expect(result.required).toContain('downloadUrl')
    expect(result.required).toContain('downloadExpiresAt')
    expect(result.properties.downloadUrl).toMatchObject({ type: 'string', format: 'uri' })
    expect(result.properties.downloadExpiresAt).toMatchObject({
      type: 'string',
      format: 'date-time',
    })
  })

  test('matches query credentials generated by the signed download implementation', () => {
    // Given: an actual synthetic signed URL from the implementation.
    const signed = createSignedTextDownload({
      baseUrl: 'https://example.com',
      token: 'synthetic-token',
      ttlSeconds: 60,
      conversationId: 'contract',
      filename: 'artifact.txt',
      nowSeconds: 100,
    })
    // When: the published path parameters are parsed.
    const route = specification.paths['/texts/{conversationId}/{filename}']
    const parameters = z
      .array(
        z.object({
          in: z.string(),
          name: z.string(),
          required: z.boolean(),
          schema: z.object({ pattern: z.string().optional() }).passthrough(),
        })
      )
      .parse(route?.parameters)
    const query = parameters.filter(value => value.in === 'query')
    // Then: GET/HEAD require exactly the credentials accepted by the signer.
    expect(query.map(value => value.name).sort()).toEqual(
      [...new URL(signed.url).searchParams.keys()].sort()
    )
    expect(query.every(value => value.required)).toBe(true)
    for (const method of ['get', 'head']) {
      const operation = z
        .object({ responses: z.record(z.string(), z.unknown()) })
        .parse(route?.[method])
      expect(Object.keys(operation.responses).sort()).toEqual(['200', '400', '403', '404'])
    }
    const signature = query.find(value => value.name === 'sig')?.schema.pattern
    if (!signature) throw new Error('Missing signature schema')
    expect(new RegExp(signature).test(new URL(signed.url).searchParams.get('sig') ?? '')).toBe(true)
  })
})
